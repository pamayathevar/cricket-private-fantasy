import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const leagueId = "10000000-0000-4000-8000-000000002026";

const squadSource = fs.readFileSync(path.join(root, "squadData.ts"), "utf8");
const squadMarker = "export const squadPlayers: Player[] = ";
const squadStart = squadSource.indexOf(squadMarker);
if (squadStart < 0) throw new Error("Could not find squadPlayers export");
const squadJsonStart = squadStart + squadMarker.length;
const squadJsonEnd = squadSource.lastIndexOf("]") + 1;
const players = JSON.parse(squadSource.slice(squadJsonStart, squadJsonEnd));

const fixtureSource = fs.readFileSync(path.join(root, "iplFixtures.ts"), "utf8");
const fixtureMatches = [...fixtureSource.matchAll(/\["([A-Z][a-z]{2} \d{1,2})","([A-Z]+) vs ([A-Z]+)"\]/g)];
const fixtures = fixtureMatches.map((match, index) => ({
  number: index + 1,
  date: match[1],
  team1: match[2],
  team2: match[3],
}));

const expectedOwners = new Set([
  "Pandiyan", "Saravana", "Sashi", "Jeba", "Johny",
  "Tamil", "Murali", "Mansur", "Bala", "Available",
]);
const expectedTeams = new Set(["CSK", "DC", "GT", "KKR", "LSG", "MI", "PBKS", "RCB", "RR", "SRH"]);
const expectedRoles = new Set(["BA", "BO", "WK", "AL"]);

if (players.length !== 268) throw new Error(`Expected 268 players, found ${players.length}`);
if (fixtures.length !== 70) throw new Error(`Expected 70 fixtures, found ${fixtures.length}`);
if (new Set(players.map((player) => `${player.team}|${player.name}`)).size !== players.length) {
  throw new Error("Duplicate player/team combination in squadData.ts");
}
for (const player of players) {
  if (!expectedOwners.has(player.owner)) throw new Error(`Unknown owner: ${player.owner}`);
  if (!expectedTeams.has(player.team)) throw new Error(`Unknown team: ${player.team}`);
  if (!expectedRoles.has(player.role)) throw new Error(`Unknown role: ${player.role}`);
  if (!Number.isFinite(player.price) || player.price < 0) throw new Error(`Invalid price: ${player.name}`);
}
for (const fixture of fixtures) {
  if (!expectedTeams.has(fixture.team1) || !expectedTeams.has(fixture.team2)) {
    throw new Error(`Unknown fixture team in match ${fixture.number}`);
  }
}

const sqlString = (value) => `'${String(value).replaceAll("'", "''")}'`;
const playerValues = players
  .map((player) => `    (${sqlString(player.name)}, ${sqlString(player.team)}, ${sqlString(player.role)}, ${player.price}, ${sqlString(player.owner)})`)
  .join(",\n");

const monthNumber = { Mar: 3, Apr: 4, May: 5 };
const matchesByDate = fixtures.reduce((map, fixture) => {
  const list = map.get(fixture.date) ?? [];
  list.push(fixture);
  map.set(fixture.date, list);
  return map;
}, new Map());

const fixtureValues = fixtures.map((fixture) => {
  const [monthName, dayText] = fixture.date.split(" ");
  const dayFixtures = matchesByDate.get(fixture.date);
  const isAfternoon = dayFixtures.length > 1 && dayFixtures[0].number === fixture.number;
  // 3:30 PM IST = 10:00 UTC; 7:30 PM IST = 14:00 UTC.
  const utcTime = isAfternoon ? "10:00:00+00" : "14:00:00+00";
  const isoDate = `2026-${String(monthNumber[monthName]).padStart(2, "0")}-${dayText.padStart(2, "0")}`;
  const status = fixture.number <= 5 ? "completed" : "scheduled";
  return `    (${fixture.number}, ${sqlString(fixture.team1)}, ${sqlString(fixture.team2)}, '${isoDate} ${utcTime}'::timestamptz, ${sqlString(status)})`;
}).join(",\n");

const migration = `-- Generated by scripts/generate-supabase-import.mjs.
-- Source snapshots: squadData.ts and iplFixtures.ts.
-- Fixture timestamps follow the official IPL convention: 7:30 PM IST, or
-- 3:30 PM IST for the first fixture on a double-header date.
begin;

create temporary table incoming_ipl2026_players (
  full_name text not null,
  team_code text not null,
  role text not null,
  acquisition_price numeric(10,2) not null,
  owner_name text not null
) on commit drop;

insert into incoming_ipl2026_players
  (full_name, team_code, role, acquisition_price, owner_name)
values
${playerValues};

do $$
begin
  if (select count(*) from incoming_ipl2026_players) <> 268 then
    raise exception 'Expected 268 incoming players';
  end if;
  if exists (
    select 1 from incoming_ipl2026_players i
    left join public.cricket_teams t on t.code = i.team_code
    where t.id is null
  ) then
    raise exception 'One or more squad teams do not exist';
  end if;
  if exists (
    select 1 from incoming_ipl2026_players i
    left join public.league_members m
      on m.league_id = '${leagueId}' and m.display_name = i.owner_name
    where i.owner_name <> 'Available' and m.id is null
  ) then
    raise exception 'One or more squad owners do not exist';
  end if;
end $$;

insert into public.players (full_name, team_id, role, active)
select i.full_name, t.id, i.role, true
from incoming_ipl2026_players i
join public.cricket_teams t on t.code = i.team_code
on conflict (full_name, team_id) do update
set role = excluded.role,
    active = true,
    updated_at = now();

-- A player can represent a different IPL team in another season. Retire the
-- league's previous pool before activating this season's exact name + team
-- identities so a stale prior-season row cannot remain selectable.
update public.league_players
set active = false,
    season_eligible = false,
    released_at = coalesce(released_at, now()),
    updated_at = now()
where league_id = '${leagueId}';

insert into public.league_players (
  league_id, player_id, owner_member_id, acquisition_type,
  acquisition_price, active, season_eligible, acquired_at, released_at
)
select
  '${leagueId}',
  p.id,
  m.id,
  case when i.owner_name = 'Available' then 'open' else 'auction' end,
  i.acquisition_price,
  true,
  true,
  case when i.owner_name = 'Available' then null else now() end,
  null
from incoming_ipl2026_players i
join public.cricket_teams t on t.code = i.team_code
join public.players p on p.full_name = i.full_name and p.team_id = t.id
left join public.league_members m
  on m.league_id = '${leagueId}' and m.display_name = i.owner_name
on conflict (league_id, player_id) do update
set owner_member_id = excluded.owner_member_id,
    acquisition_type = excluded.acquisition_type,
    acquisition_price = excluded.acquisition_price,
    active = true,
    season_eligible = true,
    acquired_at = excluded.acquired_at,
    released_at = null,
    updated_at = now();

create temporary table incoming_ipl2026_fixtures (
  match_number integer not null,
  team1_code text not null,
  team2_code text not null,
  scheduled_start timestamptz not null,
  status text not null
) on commit drop;

insert into incoming_ipl2026_fixtures
  (match_number, team1_code, team2_code, scheduled_start, status)
values
${fixtureValues};

do $$
begin
  if (select count(*) from incoming_ipl2026_fixtures) <> 70 then
    raise exception 'Expected 70 incoming fixtures';
  end if;
end $$;

insert into public.fixtures (
  league_id, external_ref, match_number, stage,
  home_team_id, away_team_id, scheduled_start, lineup_lock_at,
  status, scoring_status, scorecard_source_url
)
select
  '${leagueId}',
  'ipl-2026-m' || lpad(i.match_number::text, 2, '0'),
  i.match_number,
  'league',
  team1.id,
  team2.id,
  i.scheduled_start,
  i.scheduled_start,
  i.status,
  'pending',
  'https://www.cricinfo.com/series/ipl-2026-1510719/match-schedule-fixtures-and-results'
from incoming_ipl2026_fixtures i
join public.cricket_teams team1 on team1.code = i.team1_code
join public.cricket_teams team2 on team2.code = i.team2_code
on conflict (league_id, match_number) do update
set external_ref = excluded.external_ref,
    home_team_id = excluded.home_team_id,
    away_team_id = excluded.away_team_id,
    scheduled_start = excluded.scheduled_start,
    lineup_lock_at = excluded.lineup_lock_at,
    status = excluded.status,
    scorecard_source_url = excluded.scorecard_source_url,
    updated_at = now();

commit;
`;

const destination = path.join(root, "supabase/migrations/202608040002_import_ipl2026_squad_fixtures.sql");
fs.writeFileSync(destination, migration);
console.log(`Generated ${path.relative(root, destination)} with ${players.length} players and ${fixtures.length} fixtures.`);
